package minesweeper.view;

import java.awt.Component;
import java.awt.Dimension;

import javax.swing.JPanel;
import javax.swing.JScrollPane;
import javax.swing.JTable;
import javax.swing.SwingUtilities;
import javax.swing.event.AncestorEvent;
import javax.swing.event.AncestorListener;

import minesweeper.controller.GameTimer;
import minesweeper.controller.Minesweeper;
import minesweeper.model.LeaderBoardData;
import minesweeper.model.MsData;

public class LeaderBoard extends JPanel {

	public LeaderBoard() {

		MsData model = Minesweeper.getInstance().getModel();
		int fieldLen = model.getFieldLen();
		int amountOfMines = model.getAmountOfMines();
		String elapsedTime = GameTimer.getInstance().getTime();

		String[] columnNames = { "Platzierung", "Zeit", "Name" };
		LeaderBoardData tableModel = new LeaderBoardData(columnNames, 0); // 0 rows means dynamic amount

		tableModel.importData(fieldLen, amountOfMines); // load data from csv

		String[] userData = { elapsedTime, "" };
		tableModel.addTableRow(userData); // add new datapoint to table

		// copied from GPT
		JTable table = new JTable(tableModel);

		int rowHeight = 30;
		table.setRowHeight(rowHeight); // Set row height

		// fit 5 items at a time
		int tableHeight = 5 * rowHeight; // this line is human written

		Dimension preferredTableSize = new Dimension(table.getPreferredSize().width, tableHeight);
		table.setPreferredScrollableViewportSize(preferredTableSize);
		// end of copy

		this.add(new JScrollPane(table)); // we need a scrollpane, otherwise the header isn't shown

		int editableRowIndex = tableModel.getLastRowIndex();
		int lastColIndex = table.getColumnCount() - 1;

		// copied from GPT and modified
		table.editCellAt(editableRowIndex, lastColIndex);
		Component editor = table.getEditorComponent();
		if (editor != null) {
			table.scrollRectToVisible(table.getCellRect(editableRowIndex, lastColIndex, true)); // copied from Bing AI
																								// GPT (a few hours
																								// later)
			// defer focus request until after Swing finishes installing the editor on the
			// event dispatch thread (comment generated by GPT)
			SwingUtilities.invokeLater(editor::requestFocusInWindow); // SonarQube wanted this to be a method reference
																		// instead of a lambda for better readability
		}
		// end of copy

		// listen for events on the parent
		this.addAncestorListener(new AncestorListener() {
			@Override
			public void ancestorRemoved(AncestorEvent event) {
				// forcefully end the editing by providing invalid indices
				// data only becomes available for reading when editing has ended
				table.editCellAt(-1, -1);
				String userName = tableModel.getValueAt(editableRowIndex, lastColIndex).toString();
				tableModel.removeTableRow(editableRowIndex); // remove row that was edited from model (model is out of
																// sync with UI)
				String[] newTableRow = { elapsedTime, userName };
				tableModel.addTableRow(newTableRow); // add row with proper data (model is in sync again)

				tableModel.exportData(fieldLen, amountOfMines); // save csv file with new data
			}

			@Override
			public void ancestorAdded(AncestorEvent event) {
				// these must be here, otherwise Java complains about unimplemented methods
			}

			@Override
			public void ancestorMoved(AncestorEvent event) {
				// these must be here, otherwise Java complains about unimplemented methods
				// this duplicate comment is to make SonarQube shut up
			}
		});
	}
}
